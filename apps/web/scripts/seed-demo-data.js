async function seedAuctions() {
  const rows = auctionRecords.map((record) => {
    const { key, ...recordWithoutKey } = record;
    if (record.key === 'live') {
      return {
        ...recordWithoutKey,
        auctioneer_id: IDS.auctioneer,
        starts_at: hoursFromNow(-1),
        ends_at: hoursFromNow(6),
        preview_start: hoursFromNow(-72),
        preview_end: hoursFromNow(-6),
        pickup_start: hoursFromNow(24),
        pickup_end: hoursFromNow(120)
      };
    }
    return {
      ...recordWithoutKey,
      auctioneer_id: IDS.auctioneer,
      starts_at: hoursFromNow(48),
      ends_at: hoursFromNow(96),
      preview_start: hoursFromNow(24),
      preview_end: hoursFromNow(47),
      pickup_start: hoursFromNow(120),
      pickup_end: hoursFromNow(192)
    };
  });

  const { data, error } = await supabase
    .from('auctions')
    .upsert(rows, { onConflict: 'id' })
    .select();

  if (error) {
    throw new Error(`Failed to upsert auctions: ${error.message}`);
  }

  const map = {};
  for (const row of data) {
    const def = auctionRecords.find((a) => a.id === row.id);
    if (def) {
      map[def.key] = row;
    }
  }
  return map;
}

function buildLotRows(auctionMap) {
  const stats = {};
  for (const bid of bidRecords) {
    const lotId = IDS.lots[bid.lotKey];
    if (!stats[lotId]) {
      stats[lotId] = { bidCount: 0, highBid: 0 };
    }
    stats[lotId].bidCount += 1;
    if (bid.amount > stats[lotId].highBid) {
      stats[lotId].highBid = bid.amount;
    }
  }

  return lotRecords.map((lot) => {
    const auctionRow = auctionMap[lot.auctionKey];
    if (!auctionRow) {
      throw new Error(`Missing auction for lot key ${lot.key}`);
    }
    const lotStats = stats[lot.id] || { bidCount: 0, highBid: 0 };
    return {
      id: lot.id,
      auction_id: auctionRow.id,
      lot_number: lot.lot_number,
      title: lot.title,
      description: lot.description,
      starting_bid: lot.starting_bid,
      reserve_price: lot.reserve_price,
      increment: lot.increment,
      current_high_bid: lotStats.highBid,
      bid_count: lotStats.bidCount,
      category: lot.category,
      dimensions: null,
      condition_report: null,
      provenance: null,
      estimate_low: lot.estimate_low,
      estimate_high: lot.estimate_high,
      images: lot.images,
      is_sold: false,
      updated_at: new Date().toISOString()
    };
  });
}

async function seedLots(auctionMap) {
  const rows = buildLotRows(auctionMap);

  const { data, error } = await supabase
    .from('lots')
    .upsert(rows, { onConflict: 'id' })
    .select();

  if (error) {
    throw new Error(`Failed to upsert lots: ${error.message}`);
  }

  const map = {};
  for (const row of data) {
    const def = lotRecords.find((lot) => lot.id === row.id);
    if (def) {
      map[def.key] = row;
    }
  }
  return map;
}

async function seedBids(lotMap, userMap) {
  const lotIds = bidRecords.map((bid) => IDS.lots[bid.lotKey]);
  const uniqueLotIds = [...new Set(lotIds)];

  const { error: deleteError } = await supabase
    .from('bids')
    .delete()
    .in('lot_id', uniqueLotIds);

  if (deleteError) {
    throw new Error(`Failed to clear existing bids: ${deleteError.message}`);
  }

  const rows = bidRecords.map((bid) => {
    const lotRow = lotMap[bid.lotKey];
    const user = userMap[bid.bidderKey];
    if (!lotRow) {
      throw new Error(`Missing lot mapping for bid ${bid.id}`);
    }
    if (!user) {
      throw new Error(`Missing user mapping for bid ${bid.id}`);
    }
    return {
      id: bid.id,
      lot_id: lotRow.id,
      bidder_id: user.auth.id,
      amount: bid.amount,
      type: 'regular',
      max_amount: null,
      is_winning: bid.isWinning,
      created_at: minutesAgo(bid.minutesAgo)
    };
  });

  if (rows.length === 0) {
    return;
  }

  const { error } = await supabase.from('bids').insert(rows);
  if (error) {
    throw new Error(`Failed to insert bids: ${error.message}`);
  }
}

async function seedWallet(userMap) {
  const userIds = walletRecords
    .map((record) => userMap[record.userKey]?.auth.id)
    .filter(Boolean);

  if (userIds.length) {
    const { error: deleteError } = await supabase
      .from('wallet_ledger')
      .delete()
      .in('user_id', userIds);
    if (deleteError) {
      throw new Error(`Failed to clear existing wallet ledger rows: ${deleteError.message}`);
    }
  }

  balances.clear();
  const rows = walletRecords.map((record) => {
    const user = userMap[record.userKey];
    if (!user) {
      throw new Error(`Missing user for wallet entry ${record.id}`);
    }
    const previous = balances.get(record.userKey) || 0;
    const nextBalance = previous + record.amount;
    balances.set(record.userKey, nextBalance);
    return {
      id: record.id,
      user_id: user.auth.id,
      transaction_type: record.type,
      amount: record.amount,
      balance_after: nextBalance,
      description: record.description,
      reference_id: record.reference ? record.reference.id : null,
      reference_type: record.reference ? record.reference.type : null,
      metadata: { seed: 'demo-data' },
      created_at: minutesAgo(record.minutesAgo)
    };
  });

  if (!rows.length) {
    return;
  }

  const { error } = await supabase.from('wallet_ledger').insert(rows);
  if (error) {
    throw new Error(`Failed to insert wallet ledger entries: ${error.message}`);
  }
}

