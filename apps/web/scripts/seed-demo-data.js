const balances = new Map();

function hoursFromNow(hours) {
  return new Date(Date.now() + hours * 60 * 60 * 1000).toISOString();
}

function minutesAgo(minutes) {
  return new Date(Date.now() - minutes * 60 * 1000).toISOString();
}

async function ensureAuthUser(def) {
  const email = def.email.toLowerCase();
  try {
    const { data, error } = await supabase.auth.admin.createUser({
      email,
      password: def.password,
      email_confirm: true
    });
    if (error) {
      if (error.message && error.message.toLowerCase().includes('already registered')) {
        const existing = await findAuthUserByEmail(email);
        if (!existing) {
          throw new Error(`Auth user for ${email} exists but cannot be retrieved.`);
        }
        return existing;
      }
      throw new Error(`Failed to create auth user ${email}: ${error.message}`);
    }
    return data.user;
  } catch (error) {
    const message = typeof error?.message === 'string' ? error.message : '';
    const alreadyRegistered = message.toLowerCase().includes('already registered') ||
      message.toLowerCase().includes('already been registered') ||
      error?.code === 'email_exists';

    if (alreadyRegistered) {
      const existing = await findAuthUserByEmail(email);
      if (!existing) {
        throw new Error(`Auth user for ${email} exists but cannot be retrieved.`);
      }
      return existing;
    }

    throw error;
  }
}

async function findAuthUserByEmail(email) {
  let page = 1;
  while (true) {
    const { data, error } = await supabase.auth.admin.listUsers({ page, perPage: 1000 });
    if (error) {
      throw new Error(`Failed to list auth users: ${error.message}`);
    }
    const found = data.users.find((user) => user.email && user.email.toLowerCase() === email.toLowerCase());
    if (found) {
      return found;
    }
    if (data.users.length < 1000) {
      return null;
    }
    page += 1;
  }
}

async function ensureUserProfile(def, authUser) {
  const { error } = await supabase
    .from('users')
    .upsert(
      {
        id: authUser.id,
        email: def.email.toLowerCase(),
        role: def.role,
        first_name: def.firstName,
        last_name: def.lastName,
        phone: def.phone || null,
        is_approved: def.isApproved ?? false,
        updated_at: new Date().toISOString()
      },
      { onConflict: 'id' }
    );
  if (error) {
    throw new Error(`Failed to upsert user profile for ${def.email}: ${error.message}`);
  }
}

async function ensureUsers() {
  const userMap = {};
  for (const def of userDefinitions) {
    const authUser = await ensureAuthUser(def);
    await ensureUserProfile(def, authUser);
    userMap[def.key] = { ...def, auth: authUser };
  }
  return userMap;
}

